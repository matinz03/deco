export function SettingsSidebar() {
  const [profileOpen, setProfileOpen] = useState(false);
  const user = useAuthStore((s) => s.user);

  function scrollTo(id: string) {
    document.getElementById(id)?.scrollIntoView({ behavior: "smooth", block: "start" });
  }

  return (
    <div className="flex flex-col h-full">
      <div className="sidebar-header">
        <h2 className="sidebar-title">Settings</h2>
      </div>

      <div className="px-3 py-3 border-b border-sidebar">
        <button
          className="flex w-full items-center gap-3 rounded-xl px-3 py-2.5 transition-colors hover:bg-accent text-left"
          onClick={() => setProfileOpen(true)}
        >
          <Avatar src={user?.avatarUrl} name={user?.displayName ?? "?"} size="sm" />
          <div className="min-w-0 flex-1">
            <p className="truncate text-sm font-medium">{user?.displayName || user?.username}</p>
            <p className="truncate text-xs text-muted">@{user?.username}</p>
          </div>
          <svg className="w-3.5 h-3.5 shrink-0 text-muted" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
            <path strokeLinecap="round" strokeLinejoin="round" d="m16.862 4.487 1.687-1.688a1.875 1.875 0 1 1 2.652 2.652L10.582 16.07a4.5 4.5 0 0 1-1.897 1.13L6 18l.8-2.685a4.5 4.5 0 0 1 1.13-1.897l8.932-8.931Zm0 0L19.5 7.125" />
          </svg>
        </button>
      </div>

      <nav className="flex-1 overflow-y-auto px-3 py-3 space-y-0.5">
        {SECTIONS.map((section) => (
          <button
            key={section.id}
            className="flex w-full items-center gap-3 rounded-xl px-3 py-2.5 text-left text-sm text-muted transition-colors hover:bg-accent hover:text-foreground"
            onClick={() => scrollTo(section.id)}
          >
            <span className="shrink-0">{section.icon}</span>
            {section.label}
          </button>
        ))}
      </nav>

      <OwnProfileModal open={profileOpen} onClose={() => setProfileOpen(false)} />
    </div>
  );
}
